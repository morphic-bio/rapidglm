#!/usr/bin/env python3
"""Reference values for tests/test_vmath.cpp (written to tests/vmath_reference.hpp).

Each function of include/rapidglm/vmath.hpp at a few hundred doubles x, with
f(x) from mpmath at 60 digits written as hi + lo (hi the double nearest f(x),
lo the double nearest the rest), so that the test measures errors in units in
the last place of the correctly rounded value. The points cover each
function's hard regions: near 0, 1 and 2 (lgamma), near the root and small x
(digamma), large x, and the NB likelihood arguments y + 1/alpha for alpha from
1e-8 to 1e3.

    python3 scripts/vmath_reference.py > tests/vmath_reference.hpp
"""
import mpmath as mp

mp.mp.dps = 60
root = mp.findroot(mp.digamma, mp.mpf("1.4616321449683623"))


def points(name):
    xs = []
    lin = lambda a, b, k: [a + (b - a) * j / (k - 1) for j in range(k)]
    geo = lambda a, b, k: [float(mp.mpf(a) * (mp.mpf(b) / a) ** (mp.mpf(j) / (k - 1))) for j in range(k)]
    if name in ("log", "log1p", "lgamma", "digamma", "trigamma"):
        xs += geo(1e-300, 1e-5, 12) + geo(1e-5, 0.5, 20) + lin(0.5, 3, 40) + lin(3, 10, 20)
        xs += geo(10, 1e300, 30) + [5e-324, 2.2250738585072014e-308]
        xs += [1 + d for d in geo(1e-15, 1e-3, 10)] + [1 - d for d in geo(1e-15, 1e-3, 10)]
        xs += [2 + d for d in geo(1e-15, 1e-3, 10)] + [2 - d for d in geo(1e-15, 1e-3, 10)]
        r = float(root)
        xs += [r + d for d in geo(1e-15, 1e-3, 8)] + [r - d for d in geo(1e-15, 1e-3, 8)]
        for y in (0, 1, 2, 3, 7, 10, 100, 1000, 10000):
            xs += [y + 1 / a for a in geo(1e-8, 1e3, 8)]
    if name == "log1p":
        xs += [-d for d in geo(1e-300, 0.999999, 25)]
    if name == "lgamma":
        xs += [-2.5, -1.5, -0.5, -0.25, -3.75]
    if name == "exp":
        xs = lin(-745, 709, 60) + [d for d in geo(1e-300, 1, 20)] + [-d for d in geo(1e-300, 1, 20)]
    return sorted(set(float(x) for x in xs))


def value(name, x):
    x = mp.mpf(x)
    if name == "log":
        return mp.log(x)
    if name == "log1p":
        return mp.log1p(x)
    if name == "exp":
        return mp.exp(x)
    if name == "lgamma":
        return mp.log(abs(mp.gamma(x)))
    if name == "digamma":
        return mp.digamma(x)
    return mp.psi(1, x)


print("// Generated by scripts/vmath_reference.py (mpmath, 60 digits); do not edit.")
print("#pragma once")
print("struct VmathReference {\n    double x, hi, lo;\n};")
for name in ("log", "log1p", "exp", "lgamma", "digamma", "trigamma"):
    rows = []
    for x in points(name):
        v = value(name, x)
        hi = float(v)
        if hi in (float("inf"), float("-inf")) or hi == 0:
            continue
        lo = float(v - mp.mpf(hi))
        rows.append(f"    {{{x!r}, {hi!r}, {lo!r}}},")
    print(f"inline constexpr VmathReference vmath_reference_{name}[] = {{")
    print("\n".join(rows))
    print("};")
